// Fast lowercase lookups for case-insensitive fallback
const dictLower: Record<Lang, Record<string, string>> = {
  en: {},
  te: {},
  hi: {},
}

for (const l of ['en', 'te', 'hi'] as const) {
  for (const [k, v] of Object.entries(dict[l])) {
    dictLower[l][k.toLowerCase()] = v
  }
}

// Regex to extract leading symbols/emojis/bullet/plus/checkmarks
const PREFIX_REGEX = /^([\p{Extended_Pictographic}\u2600-\u27BF\uE000-\uF8FF⚠️✓+*·•\s-]+)\s*(?=[a-zA-Z\u0C00-\u0C7F\u0900-\u097F])/u
// Regex to extract trailing counters, badges, and punctuation
const SUFFIX_REGEX = /(\s*(\(\d+\)|\[\d+\]|[:.,!?→]+))+$/

function splitText(text: string): { prefix: string; core: string; suffix: string } {
  let s = text.trim()
  const pMatch = s.match(PREFIX_REGEX)
  const prefix = pMatch ? pMatch[0] : ''
  let rest = prefix ? s.slice(prefix.length) : s

  let suffix = ''
  const sMatch = rest.match(SUFFIX_REGEX)
  if (sMatch) {
    suffix = sMatch[0]
    rest = rest.slice(0, rest.length - suffix.length)
  }

  return { prefix, core: rest.trim(), suffix }
}

interface I18nContextValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string) => string
}

const Ctx = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const v = localStorage.getItem('bc-lang')
      return v === 'te' || v === 'hi' ? v : 'en'
    } catch {
      return 'en'
    }
  })

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('bc-lang', l)
    } catch {
      /* ignore */
    }
    // Dispatch window event so any external non-React listeners can react
    try {
      window.dispatchEvent(new CustomEvent('bc-lang-change', { detail: l }))
    } catch {
      /* ignore */
    }
  }, [])

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.setAttribute('data-lang', lang)
  }, [lang])

  // Centralized translation lookup function with fallback
  const t = useCallback(
    (key: string): string => {
      if (!key) return ''
      const trimmed = key.trim()

      if (lang === 'en') {
        return dict.en[key] ?? dict.en[trimmed] ?? key
      }

      // 1. Direct match
      if (dict[lang]?.[key]) return dict[lang][key]
      if (dict[lang]?.[trimmed]) return dict[lang][trimmed]

      // 2. Prefix / Core / Suffix extraction
      const { prefix, core, suffix } = splitText(trimmed)
      if (core) {
        if (dict[lang]?.[core]) {
          return prefix + dict[lang][core] + suffix
        }
        const lowerCore = core.toLowerCase()
        if (dictLower[lang]?.[lowerCore]) {
          return prefix + dictLower[lang][lowerCore] + suffix
        }
      }

      // Fallback to English dictionary or original key
      return dict.en[key] ?? dict.en[trimmed] ?? key
    },
    [lang]
  )

  // Real-time DOM Text & Attribute Translator that guarantees 100% of interface text across all
  // dashboards, modals, sidebars and cards translates immediately upon language switch,
  // while strictly keeping user names, emails, phone numbers, and IDs untouched.
  const observerRef = useRef<MutationObserver | null>(null)

  useEffect(() => {
    if (typeof window === 'undefined' || typeof document === 'undefined') return

    const skipTags = new Set(['SCRIPT', 'STYLE', 'INPUT', 'TEXTAREA', 'CODE', 'PRE'])

    const translateNode = (node: Text) => {
      const val = node.nodeValue
      if (!val) return
      const trimmed = val.trim()
      if (!trimmed || trimmed.length < 2) return

      // Strict user data & ID protections
      if (trimmed.includes('@') || /^[+0-9\s\-()]{7,}$/.test(trimmed)) return
      if (/^PRJ-\d+/i.test(trimmed) || /^(w|b|c|u|alt|p)-[0-9]+/i.test(trimmed)) return
      if (/^(CA|GST|REG|LIC|TXN|ISO)[\/:\s-]/i.test(trimmed)) return
      if (/^[₹$€£]\s*[\d,.]+(\s*(\/|-)\s*[\w.]+)?$/i.test(trimmed)) return

      const parent = node.parentElement
      if (!parent || skipTags.has(parent.tagName)) return
      if (parent.closest('[data-no-translate="true"]') || parent.isContentEditable) return

      const anyNode = node as any

      if (lang === 'en') {
        // Restore original English text if it was replaced earlier
        if (anyNode.__bc_orig !== undefined && anyNode.__bc_orig !== node.nodeValue) {
          node.nodeValue = anyNode.__bc_orig
        }
        return
      }

      // Check if trimmed text or decomposed core has a translation in dict[lang]
      let translated: string | undefined = dict[lang]?.[trimmed]
      let prefix = ''
      let suffix = ''

      if (!translated) {
        const split = splitText(trimmed)
        if (split.core) {
          if (dict[lang]?.[split.core]) {
            translated = dict[lang][split.core]
            prefix = split.prefix
            suffix = split.suffix
          } else {
            const lowerCore = split.core.toLowerCase()
            if (dictLower[lang]?.[lowerCore]) {
              translated = dictLower[lang][lowerCore]
              prefix = split.prefix
              suffix = split.suffix
            }
          }
        }
      }

      if (translated) {
        if (anyNode.__bc_orig === undefined) {
          anyNode.__bc_orig = val
        }
        const leading = val.match(/^\s*/)?.[0] || ''
        const trailing = val.match(/\s*$/)?.[0] || ''
        const finalVal = leading + prefix + translated + suffix + trailing
        if (node.nodeValue !== finalVal) {
          node.nodeValue = finalVal
        }
      }
    }

    const translateElement = (el: Element) => {
      if (el.closest('[data-no-translate="true"]')) return

      // Translate placeholder for inputs and textareas
      if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
        const ph = el.placeholder
        if (ph && ph.trim()) {
          const anyEl = el as any
          if (lang === 'en') {
            if (anyEl.__bc_orig_ph !== undefined) {
              el.placeholder = anyEl.__bc_orig_ph
            }
          } else {
            if (anyEl.__bc_orig_ph === undefined) {
              anyEl.__bc_orig_ph = ph
            }
            const translated = t(anyEl.__bc_orig_ph)
            if (translated && translated !== el.placeholder) {
              el.placeholder = translated
            }
          }
        }
      }

      // Translate title attribute
      const title = el.getAttribute('title')
      if (title && title.trim()) {
        const anyEl = el as any
        if (lang === 'en') {
          if (anyEl.__bc_orig_title !== undefined) {
            el.setAttribute('title', anyEl.__bc_orig_title)
          }
        } else {
          if (anyEl.__bc_orig_title === undefined) {
            anyEl.__bc_orig_title = title
          }
          const translated = t(anyEl.__bc_orig_title)
          if (translated && translated !== title) {
            el.setAttribute('title', translated)
          }
        }
      }
    }

    const walk = (root: Node) => {
      if (root.nodeType === Node.ELEMENT_NODE) {
        translateElement(root as Element)
        const els = (root as Element).querySelectorAll('input[placeholder], textarea[placeholder], [title]')
        els.forEach(translateElement)
      }

      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode(n) {
          const p = n.parentElement
          if (!p || skipTags.has(p.tagName)) return NodeFilter.FILTER_REJECT
          if (p.closest('[data-no-translate="true"]')) return NodeFilter.FILTER_REJECT
          return NodeFilter.FILTER_ACCEPT
        },
      })

      const nodes: Text[] = []
      let curr = walker.nextNode()
      while (curr) {
        nodes.push(curr as Text)
        curr = walker.nextNode()
      }

      for (const n of nodes) {
        translateNode(n)
      }
    }

    // Initial walk of body
    walk(document.body)

    // Observe future DOM changes (e.g. tab switches, modal popups, dynamic data loads)
    if (observerRef.current) {
      observerRef.current.disconnect()
    }

    let timeoutId: any = null
    const observer = new MutationObserver((mutations) => {
      clearTimeout(timeoutId)
      timeoutId = setTimeout(() => {
        for (const mut of mutations) {
          if (mut.type === 'childList') {
            mut.addedNodes.forEach((node) => {
              if (node.nodeType === Node.TEXT_NODE) {
                translateNode(node as Text)
              } else if (node.nodeType === Node.ELEMENT_NODE) {
                walk(node)
              }
            })
          } else if (mut.type === 'characterData') {
            translateNode(mut.target as Text)
          } else if (mut.type === 'attributes' && mut.target.nodeType === Node.ELEMENT_NODE) {
            translateElement(mut.target as Element)
          }
        }
      }, 50)
    })

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'title'],
    })

    observerRef.current = observer

    return () => {
      clearTimeout(timeoutId)
      observer.disconnect()
    }
  }, [lang, t])

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const c = useContext(Ctx)
  if (!c) throw new Error('useI18n must be used inside <I18nProvider>')
  return c
}
